#!/usr/bin/env python3
"""Copy the host-bridge.v2 fixtures from server-platform into a Kotlin test source.

Kotlin common tests cannot read files on every target, so the fixtures are
embedded as strings. Run this after the contract changes:

    tools/sync-host-bridge-fixtures.py ../server-platform

The output names the source commit. `--check` fails when the output is stale.
"""
import json
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "composeApp/src/commonTest/kotlin/org/formulagen/wrapper/bridge/HostBridgeFixtures.kt"


def kotlin_string(value: str) -> str:
    return '"""' + value.replace("$", "${'$'}") + '"""'


def render(root: Path) -> str:
    fixtures = root / "event-contracts/src/host-bridge/fixtures"
    commit = subprocess.run(["git", "-C", str(root), "log", "-1", "--format=%H", "--", str(fixtures)],
                            capture_output=True, text=True, check=True).stdout.strip()

    def entries(folder: str) -> str:
        files = sorted((fixtures / folder).glob("*.json"))
        return "\n".join(f"        {kotlin_string(path.name)} to {kotlin_string(json.dumps(json.loads(path.read_text()), separators=(',', ':')))},"
                         for path in files)

    parity = json.dumps(json.loads((fixtures / "parity.json").read_text()), separators=(",", ":"))
    return f"""// Generated by tools/sync-host-bridge-fixtures.py. Do not edit.
// Source: server-platform event-contracts/src/host-bridge/fixtures at {commit}
package org.formulagen.wrapper.bridge

internal object HostBridgeFixtures {{
    const val CONTEXT_ID = "6f1c2d3e-4a5b-4c6d-8e7f-901234567890"

    val ROUTER: Map<String, String> = mapOf(
{entries("router")}
    )

    val ENVELOPES: Map<String, String> = mapOf(
{entries("envelopes")}
    )

    const val PARITY = {kotlin_string(parity)}
}}
"""


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    text = render(Path(args[0]).resolve())
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT} is stale; run tools/sync-host-bridge-fixtures.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
