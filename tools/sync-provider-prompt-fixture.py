#!/usr/bin/env python3
"""Copy server-platform's provider prompt fixture into a Kotlin test source.

The server builds a task's provider text with `hovelProviderPrompt`; the companion must send the
same text byte for byte. HovelProviderPromptTest checks every case. Run this after the fixture
changes:

    tools/sync-provider-prompt-fixture.py ../server-platform

The output names the source commit. `--check` fails when the output is stale.
"""
import json
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "composeApp/src/jvmTest/kotlin/org/formulagen/wrapper/hovel/HovelProviderPromptFixture.kt"
FIXTURE = "event-contracts/src/hovel/fixtures/provider-prompt.json"


def kotlin_string(value: str) -> str:
    # JSON escapes every quote inside a string, so three in a row cannot occur; check anyway.
    assert '"""' not in value
    return '"""' + value.replace("$", "${'$'}") + '"""'


def render(root: Path) -> str:
    fixture = root / FIXTURE
    commit = subprocess.run(["git", "-C", str(root), "log", "-1", "--format=%H", "--", FIXTURE],
                            capture_output=True, text=True, check=True).stdout.strip()
    # ASCII escapes keep the Kotlin file plain; the test's JSON parser restores every character.
    text = json.dumps(json.loads(fixture.read_text(encoding="utf-8")), separators=(",", ":"))
    return f"""// Generated by tools/sync-provider-prompt-fixture.py. Do not edit.
// Source: server-platform {FIXTURE} at {commit}
package org.formulagen.wrapper.hovel

internal object HovelProviderPromptFixture {{
    val JSON = {kotlin_string(text)}
}}
"""


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    text = render(Path(args[0]).resolve())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run tools/sync-provider-prompt-fixture.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
